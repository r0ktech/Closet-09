// Build S/M/L measurements from the M values and a per-size grading step.
function grade(m, step) {
  const shift = (dir) =>
    Object.fromEntries(Object.entries(m).map(([k, v]) => [k, v + dir * (step[k] ?? 2)]));
  return { S: shift(-1), M: { ...m }, L: shift(1) };
}

